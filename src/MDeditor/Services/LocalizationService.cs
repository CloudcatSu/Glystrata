    public AppLanguage Language { get; private set; } = AppLanguage.TraditionalChinese;

    public event EventHandler? LanguageChanged;

    public string Get(string key) =>
        _resources.TryGetValue(Language, out var dictionary) && dictionary.TryGetValue(key, out var value)
            ? value
            : key;

    public void Apply(AppLanguage language)
    {
        if (Language == language)
        {
            return;
        }

        Language = language;
        LanguageChanged?.Invoke(this, EventArgs.Empty);
    }
